    target = base / "SPEC-001"
    target.mkdir(parents=True, exist_ok=True)
    (base / "README.md").write_text(README, encoding="utf-8", newline="\n")

    for name, content in FILES.items():
        (target / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"  [OK] examples/SPEC-001/{name}")

    (base / "ADR-001.md").write_text(ADR, encoding="utf-8", newline="\n")
    print("  [OK] examples/ADR-001.md")

    mdir = base / "auth-jwt"
    mdir.mkdir(parents=True, exist_ok=True)
    (mdir / "module.md").write_text(MODULE, encoding="utf-8", newline="\n")
    (mdir / "module_review.md").write_text(MODULE_REVIEW, encoding="utf-8", newline="\n")
    print("  [OK] examples/auth-jwt/module.md")
    print("  [OK] examples/auth-jwt/module_review.md")

    print("\n  样例已生成到 examples/。这是一条从 draft 走到 archived 的完整需求，")
